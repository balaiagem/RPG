EAHCell FAHArenaPlan::At(int32 Cx, int32 Cy) const
{
    if (Cx < 0 || Cy < 0 || Cx >= AHArena::GridSide || Cy >= AHArena::GridSide) return EAHCell::Meadow;
    const int32 Index = Cx * AHArena::GridSide + Cy;
    return Cells.IsValidIndex(Index) ? Cells[Index] : EAHCell::Meadow;
}

float FAHArenaPlan::HeightAt(int32 Tx, int32 Ty) const
{
    const int32 Side = AHArena::HeightSide;
    if (Heights.Num() < Side * Side) return 0.f;
    const int32 Cx = Tx < 0 ? 0 : Tx >= Side ? Side - 1 : Tx;
    const int32 Cy = Ty < 0 ? 0 : Ty >= Side ? Side - 1 : Ty;
    return Heights[Cx * Side + Cy];
}

float FAHArenaPlan::GroundAt(const FVector& Where) const
{
    // Floor, not round: a tile owns the ground from its own edge to the next
    // one, and rounding would put the seam through the middle of every tile.
    const double Tx = (Where.X + AHArena::PlayHalfSize) / AHArena::TileSize;
    const double Ty = (Where.Y + AHArena::PlayHalfSize) / AHArena::TileSize;
    return HeightAt(static_cast<int32>(FMath::FloorToInt(Tx)),
                    static_cast<int32>(FMath::FloorToInt(Ty)));
}

