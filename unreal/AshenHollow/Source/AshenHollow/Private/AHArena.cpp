FVector AHArena::CellCentre(int32 Cx, int32 Cy)
{
    return FVector((static_cast<float>(Cx) + .5f) * CellSize - PlayHalfSize,
                   (static_cast<float>(Cy) + .5f) * CellSize - PlayHalfSize, 0.f);
}

void AHArena::GateCellOf(int32 Side, int32& OutX, int32& OutY)
{
    switch (Side)
    {
        case 0:  OutX = GridSide - 1; OutY = GateCell;     break;   // +X
        case 1:  OutX = GateCell;     OutY = GridSide - 1; break;   // +Y
        case 2:  OutX = 0;            OutY = GateCell;     break;   // -X
        default: OutX = GateCell;     OutY = 0;            break;   // -Y
    }
}

FVector AHArena::GatePoint(int32 Side)
{
    int32 Gx = 0, Gy = 0;
    GateCellOf(Side, Gx, Gy);
    return CellCentre(Gx, Gy);
}

void AHArena::CellOf(const FVector& Where, int32& OutX, int32& OutY)
{
    OutX = FMath::Clamp(static_cast<int32>((Where.X + PlayHalfSize) / CellSize), 0, GridSide - 1);
    OutY = FMath::Clamp(static_cast<int32>((Where.Y + PlayHalfSize) / CellSize), 0, GridSide - 1);
}

bool AHArena::InGrid(int32 Cx, int32 Cy)
{
    return Cx >= 0 && Cy >= 0 && Cx < GridSide && Cy < GridSide;
}

