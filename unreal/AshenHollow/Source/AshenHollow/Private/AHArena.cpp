    int32 CoverWeight()
    {
        int32 Sum = 0;
        for (const FAHPropKind& Kind : GCover) Sum += Kind.Weight;
        return Sum;
    }

    const FAHPropKind& PickCover(FRandomStream& Dice)
    {
        int32 Roll = Dice.RandRange(1, CoverWeight());
        for (const FAHPropKind& Kind : GCover)
        {
            Roll -= Kind.Weight;
            if (Roll <= 0) return Kind;
        }
        return GCover[0];
    }

    /**
     * Shortest 2D distance from Point to the segment A-B, and where along it it fell.
     *
     * Everything here is double on purpose. Vector maths in UE5 is double
     * precision, so pulling a length into a float both narrows it quietly and
     * stops FMath::Clamp deducing a single type from its arguments.
     */
    double DistanceToSegment(const FVector& Point, const FVector& A, const FVector& B, double& OutAlong)
    {
        const FVector2D P(Point.X, Point.Y), Start(A.X, A.Y), End(B.X, B.Y);
        const FVector2D Span = End - Start;
        const double Length2 = Span.SizeSquared();
        OutAlong = Length2 > UE_KINDA_SMALL_NUMBER
                 ? FMath::Clamp(FVector2D::DotProduct(P - Start, Span) / Length2, 0.0, 1.0)
                 : 0.0;
        return FVector2D::Distance(P, Start + Span * OutAlong);
    }

    /**
     * A repeatable pseudo-random number in 0..1 for a lattice point.
     *
     * Deliberately a hash rather than a draw from the stream: the noise has to
     * give the same answer for cell (4,7) no matter what order the generator
     * asks in, otherwise smoothing one cell would change the landscape behind it.
     */
    float Hash01(int32 X, int32 Y, int32 Seed)
    {
        uint32 H = static_cast<uint32>(X) * 374761393u
                 + static_cast<uint32>(Y) * 668265263u
                 + static_cast<uint32>(Seed) * 2246822519u;
        H = (H ^ (H >> 13)) * 1274126177u;
        H ^= (H >> 16);
        return static_cast<float>(H & 0xFFFFFFu) / static_cast<float>(0xFFFFFF);
    }

    /**
     * Smooth value noise. Blobs, not salt and pepper -- which is the entire
     * reason the landscape comes from noise instead of from a die per cell.
     */
    float ValueNoise(float X, float Y, int32 Seed)
    {
        const int32 X0 = FMath::FloorToInt(X);
        const int32 Y0 = FMath::FloorToInt(Y);
        const float Fx = X - static_cast<float>(X0);
        const float Fy = Y - static_cast<float>(Y0);
        const float Sx = Fx * Fx * (3.f - 2.f * Fx);
        const float Sy = Fy * Fy * (3.f - 2.f * Fy);
        const float Low  = FMath::Lerp(Hash01(X0, Y0,     Seed), Hash01(X0 + 1, Y0,     Seed), Sx);
        const float High = FMath::Lerp(Hash01(X0, Y0 + 1, Seed), Hash01(X0 + 1, Y0 + 1, Seed), Sx);
        return FMath::Lerp(Low, High, Sy);
    }

    int32 Chebyshev(int32 AX, int32 AY, int32 BX, int32 BY)
    {
        return FMath::Max(FMath::Abs(AX - BX), FMath::Abs(AY - BY));
    }

